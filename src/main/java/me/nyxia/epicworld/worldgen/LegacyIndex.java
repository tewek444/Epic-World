/**
 * Chunks that already existed when the current Epic World settings were first applied to a save. New chunks blend
 * towards their terrain; their blocks are never rewritten.
 *
 * <p>The set is captured once per settings fingerprint from region-file headers (no chunk is generated or loaded to
 * find it). Surface heights are read lazily from the saved chunk NBT.
 */
public final class LegacyIndex {
    private static volatile LegacyIndex current;

    private final ServerLevel level;
    private final LongSet legacy;
    private final LongSet legacyRegions = new LongOpenHashSet();
    private final int legacyMinY;
    private final int blendingDistance;
    private final Map<Long, Optional<Surface>> heights = new ConcurrentHashMap<>();

    private LegacyIndex(ServerLevel level, LongSet legacy, int legacyMinY, int blendingDistance) {
        this.level = level;
        this.legacy = legacy;
        this.legacyMinY = legacyMinY;
        this.blendingDistance = blendingDistance;
        for (long pos : legacy) legacyRegions.add(ChunkPos.asLong(ChunkPos.getX(pos) >> 5, ChunkPos.getZ(pos) >> 5));
    }

    @Nullable
    public static LegacyIndex current(ServerLevel level) {
        LegacyIndex index = current;
        return index != null && index.level == level ? index : null;
    }

    @Nullable
    public static LegacyIndex currentAny() { return current; }

    public static void clear() { current = null; }

    /** Called when the Overworld loads, before spawn chunks are prepared. */
    public static void load(ServerLevel level, EpicSettings settings) {
        int fingerprint = GenerationStamp.fingerprint(settings);
        var data = level.getDataStorage().computeIfAbsent(Data.FACTORY, "epicworld_generation");
        if (data.fingerprint != fingerprint || data.version != EpicSettings.GENERATOR_VERSION) {
            Path regionDir = level.getServer().getWorldPath(LevelResource.ROOT).resolve("region");
            LongSet existing = withTerrain(level, scanRegions(regionDir));
            if (!existing.isEmpty()) {
                EpicWorld.LOGGER.info("Epic World: {} existing Overworld chunks keep their terrain; new chunks blend into them",
                        existing.size());
            }
            data.legacy.addAll(existing);
            data.fingerprint = fingerprint;
            data.version = EpicSettings.GENERATOR_VERSION;
            data.legacyMinY = level.getMinBuildHeight();
            data.setDirty();
        }
        var compat = settings.compatibility();
        current = new LegacyIndex(level, data.legacy, data.legacyMinY, compat.terrainBlending() ? compat.blendingDistance() : 0);
    }

    /**
     * Keeps the chunks that already had terrain. Region files also hold unfinished chunks around explored areas
     * (saved before their noise step); those will be generated by Epic World and must blend like any new chunk.
     * Chunk data is read in small batches so only one batch is held in memory.
     */
    private static LongSet withTerrain(ServerLevel level, LongSet candidates) {
        LongSet result = new LongOpenHashSet();
        long[] keys = candidates.toLongArray();
        int batch = 256;
        for (int start = 0; start < keys.length; start += batch) {
            int end = Math.min(keys.length, start + batch);
            var reads = new java.util.ArrayList<java.util.concurrent.CompletableFuture<Optional<CompoundTag>>>(end - start);
            for (int i = start; i < end; i++) reads.add(level.getChunkSource().chunkMap.read(new ChunkPos(keys[i])));
            for (int i = start; i < end; i++) {
                try {
                    CompoundTag tag = reads.get(i - start).get(60, TimeUnit.SECONDS).orElse(null);
                    if (tag != null && hasTerrain(tag)) result.add(keys[i]);
                } catch (Exception e) {
                    // Unknown state: treat as existing terrain, which only protects it.
                    result.add(keys[i]);
                }
            }
        }
        return result;
    }

    private static final Pattern REGION = Pattern.compile("r\\.(-?\\d+)\\.(-?\\d+)\\.mca");

    static LongSet scanRegions(Path regionDir) {
        LongSet found = new LongOpenHashSet();
        if (!Files.isDirectory(regionDir)) return found;
        try (var files = Files.list(regionDir)) {
            for (Path file : (Iterable<Path>) files::iterator) {
                var m = REGION.matcher(file.getFileName().toString());
                if (!m.matches() || Files.size(file) < 8192) continue;
                int rx = Integer.parseInt(m.group(1));
                int rz = Integer.parseInt(m.group(2));
                try (InputStream in = Files.newInputStream(file); var data = new DataInputStream(in)) {
                    for (int i = 0; i < 1024; i++) {
                        if (data.readInt() != 0) found.add(ChunkPos.asLong(rx * 32 + (i & 31), rz * 32 + (i >> 5)));
                    }
                }
            }
        } catch (IOException e) {
            EpicWorld.LOGGER.error("Epic World: cannot scan region files in {}", regionDir, e);
        }
        return found;
    }

    public boolean isEmpty() { return legacy.isEmpty(); }

    /** Width of the transition around old chunks, in blocks (0 when blending is off). */
    public int blendingDistance() { return blendingDistance; }

    public boolean isLegacy(int chunkX, int chunkZ) { return legacy.contains(ChunkPos.asLong(chunkX, chunkZ)); }

    /** True when some legacy chunk may lie within {@code radiusChunks} of the given chunk. */
    public boolean anyNear(int chunkX, int chunkZ, int radiusChunks) {
        if (legacy.isEmpty()) return false;
        int r0x = (chunkX - radiusChunks) >> 5;
        int r1x = (chunkX + radiusChunks) >> 5;
        int r0z = (chunkZ - radiusChunks) >> 5;
        int r1z = (chunkZ + radiusChunks) >> 5;
        for (int rx = r0x; rx <= r1x; rx++) {
            for (int rz = r0z; rz <= r1z; rz++) {
                if (legacyRegions.contains(ChunkPos.asLong(rx, rz))) return true;
            }
        }
        return false;
    }

    /** No water in a cell of {@link Surface#water}. */
    public static final short DRY = Short.MIN_VALUE;

    /**
     * Saved surface of a legacy chunk. On a 4×4 grid (index {@code x/4 + 4*(z/4)}): {@code ground} is the top solid
     * block, {@code water} the top water block of cells that are mostly covered by water, or {@link #DRY}, and
     * {@code biomes} the biome id at the surface (null when unknown). {@code fineGround} has every column
     * (index {@code x + 16*z}), for matching the old surface exactly at the border.
     */
    public record Surface(short[] ground, short[] water, short[] fineGround, String[] biomes) {}

    /**
     * Terrain surface of a legacy chunk, or empty when the chunk had no terrain yet. Ground uses
     * min(OCEAN_FLOOR, MOTION_BLOCKING_NO_LEAVES) so leaves and water do not count; cell medians remove single-column
     * spikes such as tree trunks. Water is where MOTION_BLOCKING_NO_LEAVES stands above OCEAN_FLOOR.
     */
    public Optional<Surface> surface(int chunkX, int chunkZ) {
        long key = ChunkPos.asLong(chunkX, chunkZ);
        if (!legacy.contains(key)) return Optional.empty();
        return heights.computeIfAbsent(key, k -> read(new ChunkPos(chunkX, chunkZ)));
    }

    private Optional<Surface> read(ChunkPos pos) {
        CompoundTag tag;
        try {
            tag = level.getChunkSource().chunkMap.read(pos).get(20, TimeUnit.SECONDS).orElse(null);
        } catch (Exception e) {
            EpicWorld.LOGGER.warn("Epic World: cannot read legacy chunk {} for blending", pos, e);
            return Optional.empty();
        }
        if (tag == null) return Optional.empty();
        return parseSurface(tag, legacyMinY);
    }

    /**
     * Reads the surface of a saved chunk (see {@link #surface}). Heightmaps are relative to the bottom of the world the
     * chunk was saved in ({@code yPos}), which may differ from the current one; {@code fallbackMinY} is used when the
     * tag has no {@code yPos}. Empty for chunks saved before their noise step.
     */
    public static Optional<Surface> parseSurface(CompoundTag tag, int fallbackMinY) {
        if (!hasTerrain(tag)) return Optional.empty();
        int minY = tag.contains("yPos", Tag.TAG_ANY_NUMERIC) ? tag.getInt("yPos") * 16 : fallbackMinY;
        CompoundTag maps = tag.getCompound("Heightmaps");
        int[] floor = decode(maps, minY, "OCEAN_FLOOR", "OCEAN_FLOOR_WG");
        int[] noLeaves = decode(maps, minY, "MOTION_BLOCKING_NO_LEAVES", "WORLD_SURFACE_WG");
        if (floor == null && noLeaves == null) return Optional.empty();
        int[] surface = new int[256];
        for (int i = 0; i < 256; i++) {
            int a = floor == null ? Integer.MAX_VALUE : floor[i];
            int b = noLeaves == null ? Integer.MAX_VALUE : noLeaves[i];
            surface[i] = Math.min(a, b);
        }
        short[] grid = new short[16];
        short[] water = new short[16];
        for (int gz = 0; gz < 4; gz++) {
            for (int gx = 0; gx < 4; gx++) {
                // Median of the 4×4 block: robust against trunks, pillars and small pits.
                int[] cell = new int[16];
                int[] wet = new int[16];
                int n = 0;
                int w = 0;
                for (int dz = 0; dz < 4; dz++) {
                    for (int dx = 0; dx < 4; dx++) {
                        int i = (gx * 4 + dx) + 16 * (gz * 4 + dz);
                        cell[n++] = surface[i];
                        if (floor != null && noLeaves != null && noLeaves[i] > floor[i]) wet[w++] = noLeaves[i];
                    }
                }
                java.util.Arrays.sort(cell);
                grid[gx + 4 * gz] = (short) ((cell[7] + cell[8]) / 2);
                if (w >= 8) {
                    java.util.Arrays.sort(wet, 0, w);
                    water[gx + 4 * gz] = (short) wet[w / 2];
                } else {
                    water[gx + 4 * gz] = DRY;
                }
            }
        }
        short[] fine = new short[256];
        for (int i = 0; i < 256; i++) fine[i] = (short) surface[i];
        return Optional.of(new Surface(grid, water, fine, surfaceBiomes(tag, grid, minY)));
    }

    /** Biome ids at the surface of each 4×4 cell, read from the section biome palettes. */
    private static String[] surfaceBiomes(CompoundTag tag, short[] grid, int minY) {
        String[] out = new String[16];
        var sections = new java.util.HashMap<Integer, CompoundTag>();
        for (Tag t : tag.getList("sections", Tag.TAG_COMPOUND)) {
            var section = (CompoundTag) t;
            if (section.contains("biomes", Tag.TAG_COMPOUND)) sections.put((int) section.getByte("Y"), section.getCompound("biomes"));
        }
        for (int cell = 0; cell < 16; cell++) {
            int y = Math.max(minY, grid[cell]);
            var biomes = sections.get(Math.floorDiv(y, 16));
            if (biomes == null) continue;
            var palette = biomes.getList("palette", Tag.TAG_STRING);
            if (palette.isEmpty()) continue;
            if (palette.size() == 1) {
                out[cell] = palette.getString(0);
                continue;
            }
            long[] data = biomes.getLongArray("data");
            int bits = Math.max(1, Mth.ceillog2(palette.size()));
            int perLong = 64 / bits;
            if (data.length != (64 + perLong - 1) / perLong) continue;
            int qx = cell & 3;
            int qz = cell >> 2;
            int qy = (Math.floorMod(y, 16)) >> 2;
            int i = (qy * 4 + qz) * 4 + qx;
            int value = (int) ((data[i / perLong] >>> ((i % perLong) * bits)) & ((1L << bits) - 1));
            if (value < palette.size()) out[cell] = palette.getString(value);
        }
        return out;
    }

    private static final java.util.Set<String> BEFORE_NOISE = java.util.Set.of("empty", "structure_starts",
            "structure_references", "biomes");

    /**
     * True when a saved chunk already has terrain (its noise step ran). Compared by name so it also works without a
     * running game (world conversion planning).
     */
    public static boolean hasTerrain(CompoundTag tag) {
        String status = tag.getString("Status");
        if (status.startsWith("minecraft:")) status = status.substring("minecraft:".length());
        return !status.isEmpty() && !BEFORE_NOISE.contains(status);
    }

    /** Decodes a heightmap to the Y of the top block per column; the bit width is derived from the array length. */
    @Nullable
    private static int[] decode(CompoundTag maps, int minY, String... names) {
        for (String name : names) {
            if (!maps.contains(name, Tag.TAG_LONG_ARRAY)) continue;
            long[] raw = ((LongArrayTag) maps.get(name)).getAsLongArray();
            if (raw.length == 0) continue;
            int bits = 0;
            for (int b = 1; b <= 32; b++) {
                if ((256 + (64 / b) - 1) / (64 / b) == raw.length) {
                    bits = b;
                    break;
                }
            }
            if (bits == 0) continue;
            try {
                var storage = new SimpleBitStorage(bits, 256, raw);
                int[] out = new int[256];
                for (int i = 0; i < 256; i++) out[i] = storage.get(i) + minY - 1;
                return out;
            } catch (RuntimeException ignored) {
                // Malformed heightmap: try the next one.
            }
        }
        return null;
    }

    /** Persistent part: the legacy set and the fingerprint it belongs to. */
    public static final class Data extends SavedData {
        static final Factory<Data> FACTORY = new Factory<>(Data::new, Data::load);
        int fingerprint;
        int version;
        int legacyMinY;
        final LongSet legacy = new LongOpenHashSet();

        static Data load(CompoundTag tag, HolderLookup.Provider registries) {
            var data = new Data();
            data.fingerprint = tag.getInt("fingerprint");
            data.version = tag.getInt("version");
            data.legacyMinY = tag.getInt("legacy_min_y");
            for (long pos : tag.getLongArray("legacy")) data.legacy.add(pos);
            return data;
        }

        @Override
        public CompoundTag save(CompoundTag tag, HolderLookup.Provider registries) {
            tag.putInt("fingerprint", fingerprint);
            tag.putInt("version", version);
            tag.putInt("legacy_min_y", legacyMinY);
            tag.putLongArray("legacy", legacy.toLongArray());
            return tag;
        }
    }
}
